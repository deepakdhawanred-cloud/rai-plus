export function buildVisNovember2026Timetable(): TimetableSlot[] {
  const slots: TimetableSlot[] = [];
  for (const classSection of VIS_CLASS_ORDER) {
    const classDays = RAW_TIMETABLE_GRIDS[classSection];
    if (!classDays) continue;
    for (const day of VIS_DAYS) {
      const cells = classDays[day] || [];
      for (let i = 0; i < cells.length; i += 1) {
        const cell = cells[i];
        if (!cell) continue;
        const period = i + 1;
        const [subject, teacherName] = cell;
        const slug = `${classSection}-${day.slice(0, 3)}-p${period}`
          .toLowerCase()
          .replace(/[^a-z0-9-]+/g, '-');
        slots.push({
          id: `tt-vis-nov-${slug}`,
          schoolId: 'school-vis-jjr',
          day,
          period,
          timeRange: TIME_BY_PERIOD[period] || '09:05–09:40',
          classSection,
          subject,
          teacherName,
        });
      }
    }
  }
  return slots;
}

export const VIS_TIMETABLE_NOV_2026: TimetableSlot[] = buildVisNovember2026Timetable();
